const root = document.documentElement;
const langToggle = document.querySelector("#langToggle");
const themeToggle = document.querySelector("#themeToggle");
const translatable = document.querySelectorAll("[data-i18n]");
const plantMood = document.querySelector("#plantMood");

let currentLang = localStorage.getItem("yaowen-lang") || "zh";
let currentTheme = localStorage.getItem("yaowen-theme") || "light";
let currentGarden = "morning";

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("yaowen-lang", lang);
  root.lang = lang === "zh" ? "zh-Hant" : "en";
  langToggle.textContent = lang === "zh" ? "EN" : "中";

  translatable.forEach((node) => {
    const key = node.dataset.i18n;
    if (copy[lang][key]) node.innerHTML = copy[lang][key];
  });

  updateGardenMood(currentGarden, false);
  if (window.gsap) {
    gsap.fromTo("[data-i18n]", { y: 6, opacity: 0.7 }, { y: 0, opacity: 1, duration: 0.38, stagger: 0.006, ease: "power2.out" });
  }
}

function setTheme(theme) {
  currentTheme = theme;
  localStorage.setItem("yaowen-theme", theme);
  root.dataset.theme = theme;
}

function setPalette(palette) {
  root.dataset.palette = palette === "fern" ? "" : palette;
  document.querySelectorAll(".swatch").forEach((button) => {
    button.classList.toggle("active", button.dataset.palette === palette);
  });
  if (window.gsap) {
    gsap.fromTo("body", { filter: "saturate(1.25) brightness(1.03)" }, { filter: "saturate(1) brightness(1)", duration: 0.55, ease: "power2.out" });
  }
}

function updateGardenMood(mode, animate = true) {
  currentGarden = mode;
  if (plantMood) plantMood.textContent = gardenMessages[currentLang][mode];

  document.querySelectorAll(".control-card").forEach((button) => {
    button.classList.toggle("active", button.dataset.garden === mode);
  });

  if (!window.gsap || !animate) return;

  const stage = document.querySelector(".plant-stage");
  const leaves = ".plant-leaf";
  const moodMap = {
    morning: { scale: 1, rotate: 0, hue: 0, y: 0 },
    rain: { scale: 1.08, rotate: -3, hue: -16, y: 8 },
    sunset: { scale: 1.03, rotate: 4, hue: 22, y: -4 }
  };
  const mood = moodMap[mode];

  gsap.to(stage, { filter: `hue-rotate(${mood.hue}deg)`, duration: 0.45, ease: "power2.out" });
  gsap.to(leaves, {
    scale: mood.scale,
    y: mood.y,
    rotate: (index) => (index % 2 ? mood.rotate : -mood.rotate),
    duration: 0.72,
    stagger: 0.04,
    ease: "elastic.out(1, 0.45)"
  });
  gsap.fromTo(plantMood, { y: 8, opacity: 0.45 }, { y: 0, opacity: 1, duration: 0.4, ease: "power2.out" });
}

function filterWorks(kind) {
  document.querySelectorAll(".filter-button").forEach((button) => {
    button.classList.toggle("active", button.dataset.filter === kind);
  });

  document.querySelectorAll(".work-card").forEach((card) => {
    const show = kind === "all" || card.dataset.kind === kind;
    card.classList.toggle("is-hidden", !show);
    if (show && window.gsap) {
      gsap.fromTo(card, { y: 18, opacity: 0, scale: 0.98 }, { y: 0, opacity: 1, scale: 1, duration: 0.38, ease: "power2.out" });
    }
  });
}

langToggle.addEventListener("click", () => setLanguage(currentLang === "zh" ? "en" : "zh"));
themeToggle.addEventListener("click", () => {
  setTheme(currentTheme === "light" ? "dark" : "light");
  if (window.gsap) gsap.fromTo("body", { filter: "saturate(1.2)" }, { filter: "saturate(1)", duration: 0.45, ease: "power2.out" });
});

document.querySelectorAll(".control-card").forEach((button) => {
  button.addEventListener("click", () => updateGardenMood(button.dataset.garden));
});

document.querySelectorAll(".swatch").forEach((button) => {
  button.addEventListener("click", () => setPalette(button.dataset.palette));
});

document.querySelectorAll(".filter-button").forEach((button) => {
  button.addEventListener("click", () => filterWorks(button.dataset.filter));
});

