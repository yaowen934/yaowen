function initAnimations() {
  if (!window.gsap) return;
  if (window.ScrollTrigger) gsap.registerPlugin(ScrollTrigger);

  const intro = gsap.timeline({ defaults: { ease: "power3.out" } });
  intro
    .from(".site-header", { y: -24, opacity: 0, duration: 0.65 })
    .from(".hero .eyebrow", { y: 18, opacity: 0, duration: 0.55 }, "-=0.25")
    .from(".hero h1", { y: 42, opacity: 0, duration: 0.9 }, "-=0.25")
    .from(".hero-text", { y: 22, opacity: 0, duration: 0.72 }, "-=0.42")
    .from(".hero-actions a", { y: 14, opacity: 0, duration: 0.55, stagger: 0.1 }, "-=0.35")
    .from(".portrait-shell", { rotateY: -12, rotateX: 8, y: 34, opacity: 0, duration: 1 }, "-=0.8")
    .from(".metric", { scale: 0.78, opacity: 0, duration: 0.55, stagger: 0.1 }, "-=0.45");

  gsap.to(".leaf-a", { y: -14, rotate: -20, duration: 4.8, repeat: -1, yoyo: true, ease: "sine.inOut" });
  gsap.to(".leaf-b", { y: 12, rotate: 42, duration: 5.4, repeat: -1, yoyo: true, ease: "sine.inOut" });
  gsap.to(".leaf-c", { x: 8, y: -8, rotate: 26, duration: 4.2, repeat: -1, yoyo: true, ease: "sine.inOut" });
  gsap.to(".growth-line", { y: -170, opacity: 0.18, duration: 2.8, repeat: -1, yoyo: true, ease: "sine.inOut" });
  gsap.to(".brand-mark", { borderRadius: "56% 44% 58% 42% / 44% 58% 42% 56%", duration: 3.2, repeat: -1, yoyo: true, ease: "sine.inOut" });

  gsap.utils.toArray(".section-heading").forEach((heading) => {
    gsap.from(heading.children, {
      scrollTrigger: { trigger: heading, start: "top 84%" },
      y: 34,
      opacity: 0,
      duration: 0.72,
      stagger: 0.12,
      ease: "power2.out"
    });
  });

  gsap.utils.toArray(".highlight-strip article, .timeline-item, .garden-lab, .palette-board, .work-card, .service-card, .contact-panel").forEach((item, index) => {
    gsap.from(item, {
      scrollTrigger: { trigger: item, start: "top 88%" },
      y: 42,
      opacity: 0,
      rotate: index % 2 ? 1.2 : -1.2,
      duration: 0.76,
      ease: "power2.out"
    });
  });

  gsap.utils.toArray(".plant-leaf").forEach((leaf, index) => {
    gsap.to(leaf, {
      rotate: `+=${index % 2 ? 8 : -8}`,
      y: index % 2 ? -10 : 10,
      duration: 2.8 + index * 0.35,
      repeat: -1,
      yoyo: true,
      ease: "sine.inOut"
    });
  });

  document.querySelectorAll(".magnetic").forEach((element) => {
    element.addEventListener("mousemove", (event) => {
      const rect = element.getBoundingClientRect();
      const x = event.clientX - rect.left - rect.width / 2;
      const y = event.clientY - rect.top - rect.height / 2;
      gsap.to(element, { x: x * 0.18, y: y * 0.18, duration: 0.28, ease: "power2.out" });
    });
    element.addEventListener("mouseleave", () => {
      gsap.to(element, { x: 0, y: 0, duration: 0.42, ease: "elastic.out(1, 0.35)" });
    });
  });

  const shell = document.querySelector(".portrait-shell");
  if (shell) {
    shell.addEventListener("mousemove", (event) => {
      const rect = shell.getBoundingClientRect();
      const x = (event.clientX - rect.left) / rect.width - 0.5;
      const y = (event.clientY - rect.top) / rect.height - 0.5;
      gsap.to(shell, { rotateY: x * 10, rotateX: -y * 10, duration: 0.45, ease: "power2.out" });
    });
    shell.addEventListener("mouseleave", () => {
      gsap.to(shell, { rotateY: 0, rotateX: 0, duration: 0.7, ease: "elastic.out(1, 0.35)" });
    });
  }
}

function initLeaves() {
  const canvas = document.querySelector("#leafCanvas");
  if (!canvas) return;

  const context = canvas.getContext("2d");
  const leaves = [];
  let width = 0;
  let height = 0;

  function resize() {
    const ratio = window.devicePixelRatio || 1;
    width = canvas.width = window.innerWidth * ratio;
    height = canvas.height = window.innerHeight * ratio;
    canvas.style.width = `${window.innerWidth}px`;
    canvas.style.height = `${window.innerHeight}px`;
    leaves.length = 0;

    const count = Math.min(48, Math.floor(window.innerWidth / 24));
    for (let index = 0; index < count; index += 1) {
      leaves.push({
        x: Math.random() * width,
        y: Math.random() * height,
        size: (Math.random() * 12 + 8) * ratio,
        speed: (Math.random() * 0.35 + 0.18) * ratio,
        drift: (Math.random() * 0.45 + 0.12) * ratio,
        angle: Math.random() * Math.PI * 2,
        spin: (Math.random() - 0.5) * 0.015,
        alpha: Math.random() * 0.16 + 0.12
      });
    }
  }

  function drawLeaf(leaf) {
    context.save();
    context.translate(leaf.x, leaf.y);
    context.rotate(leaf.angle);
    context.globalAlpha = root.dataset.theme === "dark" ? leaf.alpha * 0.8 : leaf.alpha;
    context.fillStyle = getComputedStyle(root).getPropertyValue("--leaf").trim() || "#2f8f46";
    context.beginPath();
    context.ellipse(0, 0, leaf.size * 0.62, leaf.size * 0.28, 0, 0, Math.PI * 2);
    context.fill();
    context.strokeStyle = getComputedStyle(root).getPropertyValue("--leaf-deep").trim() || "#0f5f38";
    context.lineWidth = Math.max(1, leaf.size * 0.06);
    context.beginPath();
    context.moveTo(-leaf.size * 0.42, 0);
    context.lineTo(leaf.size * 0.42, 0);
    context.stroke();
    context.restore();
  }

  function animate() {
    context.clearRect(0, 0, width, height);
    leaves.forEach((leaf) => {
      leaf.y += leaf.speed;
      leaf.x += Math.sin(leaf.angle) * leaf.drift;
      leaf.angle += leaf.spin;

      if (leaf.y > height + 40) {
        leaf.y = -40;
        leaf.x = Math.random() * width;
      }
      drawLeaf(leaf);
    });
    context.globalAlpha = 1;
    requestAnimationFrame(animate);
  }

  resize();
  animate();
  window.addEventListener("resize", resize);
}
